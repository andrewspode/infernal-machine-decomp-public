/*
 * Count-fit block generators.
 *
 * A count-fit block is a labelled run of placeholder declarations whose only job is to add a known number of entries to
 * the compiler's tables ahead of the code it fits. This section only DEFINES macros, which add no entry. It lives in
 * this header, not in a header of its own, because opening any NEW file costs the compiler exactly one count (an empty
 * guarded header shifts every serial by 1; a repeated include of an
 * already opened header shifts none), and every translation unit already opens this file through its own header.
 *
 *   CF_PROTO(name, n)        void name(int .., n parameters);   1 + n entries (n = 0 spells `void`: 1 entry)
 *   CF_PROTOS(stem, n, k)    k such prototypes in a row, named stem + a letter path, each with n parameters
 *   CF_EXTERNS(stem, k)      extern int stem..;  k times, k entries (for blocks inside a function body)
 *
 * The names are made unique by pasting `a`/`b` path letters onto the stem (and onto the parameter stems `a`, `b`, `c`..),
 * so every entry stays distinct; a duplicated name would silently drop an entry. The counts are built from power-of-two
 * blocks (CF_P<2^i> parameters, CF_F<2^i> prototypes, CF_X<2^i> externs), which are also usable directly.
 * A call is written on the line(s) the block's text occupied, so no __LINE__ moves.
 */

#define CF_CAT_(a, b) a##b
#define CF_CAT(a, b) CF_CAT_(a, b)

